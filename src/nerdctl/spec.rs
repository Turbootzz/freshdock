//! Rebuilding a container with `nerdctl create`.
//!
//! nerdctl has no "create from this JSON" call, so a container's settings are
//! read back from three places and turned into command-line flags:
//!
//! - `nerdctl inspect` (Docker-compatible): env, user, labels, mounts, the
//!   command as `Path` + `Args`, and `HostConfig`;
//! - `nerdctl inspect --mode=native`: the working directory and terminal, which
//!   the compatible output leaves out;
//! - `network-config.json` in the container's state directory: the published
//!   ports, which inspect only reports while the container is running.
//!
//! A setting freshdock cannot reproduce is recorded in
//! [`NerdctlSpec::unsupported`] instead of being dropped, and the update is
//! refused before the container is stopped.

use std::collections::HashMap;

use serde::Deserialize;
use serde_json::{Map, Value};

use crate::docker::spec::is_daemon_assigned_hostname;

/// Label prefixes nerdctl and containerd manage themselves. They are
/// regenerated by `nerdctl create`, never passed back.
const RUNTIME_LABEL_PREFIXES: [&str; 3] = ["nerdctl/", "containerd.io/", "io.containerd."];

/// `nerdctl/*` labels freshdock understands: either reproduced from another
/// source, or bookkeeping nerdctl writes for every container. Any other
/// `nerdctl/*` label is a setting freshdock doesn't know how to reproduce.
const KNOWN_NERDCTL_LABELS: [&str; 23] = [
    "nerdctl/anonymous-volumes",
    "nerdctl/auto-remove",
    "nerdctl/dns",
    "nerdctl/error",
    "nerdctl/extraHosts",
    "nerdctl/healthcheck",
    "nerdctl/healthstate",
    "nerdctl/host-config",
    "nerdctl/hostname",
    "nerdctl/ipc",
    "nerdctl/log-config",
    "nerdctl/log-uri",
    "nerdctl/name",
    "nerdctl/namespace",
    "nerdctl/networks",
    "nerdctl/platform",
    "nerdctl/state-dir",
    "nerdctl/stop-timeout",
    "nerdctl/user",
    "nerdctl/ports",
    "nerdctl/privileged",
    "nerdctl/domainname",
    "nerdctl/mac-address",
];

const STOP_SIGNAL_LABEL: &str = "io.containerd.image.config.stop-signal";
const STOP_TIMEOUT_LABEL: &str = "nerdctl/stop-timeout";

/// Everything needed to re-create one container with nerdctl.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct NerdctlSpec {
    /// Every label, as inspected (runtime-managed ones included, since shared
    /// code reads e.g. the stop timeout from them).
    pub labels: HashMap<String, String>,
    /// `None` for a hostname nerdctl assigned itself (the short id).
    pub hostname: Option<String>,
    /// Networks to join, in order; `container:<id>` shares another
    /// container's network namespace.
    pub networks: Vec<String>,
    /// `-p` values: `hostIP:hostPort:containerPort/protocol`.
    pub ports: Vec<String>,
    pub dns: Vec<String>,
    pub dns_options: Vec<String>,
    pub dns_search: Vec<String>,
    pub extra_hosts: Vec<String>,
    pub mac_address: Option<String>,
    /// Every other flag, already rendered (`["--memory", "268435456", …]`).
    pub flags: Vec<String>,
    /// `KEY=VALUE` environment variables. Never passed as `--env`: arguments
    /// are world-readable in `/proc`, and values are often secrets. They go
    /// through an owner-only `--env-file` (see [`env_file`](Self::env_file)).
    pub env: Vec<String>,
    /// `--entrypoint` value: the container's `Path`.
    pub entrypoint: Option<String>,
    /// Arguments after the image: the container's `Args`.
    pub args: Vec<String>,
    /// Settings freshdock can't reproduce; a non-empty list refuses the update.
    pub unsupported: Vec<String>,
}

/// The parts of the Docker-compatible inspect a rebuild needs.
#[derive(Debug, Clone, Default, Deserialize)]
#[serde(rename_all = "PascalCase")]
pub struct CreateInspect {
    pub id: Option<String>,
    pub path: Option<String>,
    pub args: Option<Vec<String>>,
    pub config: Option<CreateConfig>,
    pub host_config: Option<Map<String, Value>>,
    pub network_settings: Option<NetworkSettings>,
}

